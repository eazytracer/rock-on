#!/usr/bin/env python3
"""Rebuild design/demo/screens-bundle.js from design/demo/screens/*.html + design/source/kit/.

The mobile demo loads each locked screen page into an iframe. With the bundle loaded,
it uses `srcdoc` instead of `src`, which works when the demo is opened straight from
disk (file://), where browsers block reaching into a file iframe.

Run after changing any screen page or kit file:
    python3 design/tools/build-screens-bundle.py
"""
import base64
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
SCREENS = ROOT / "demo" / "screens"
KIT = ROOT / "source" / "kit"
OUT = ROOT / "demo" / "screens-bundle.js"

kit = {}
for f in sorted(KIT.iterdir()):
    if f.suffix in (".css", ".js"):
        text = f.read_text(encoding="utf-8")
        # Inlined into a <script> / <style> element: a literal "</script" would end it early.
        kit[f.name] = text.replace("</script", "<\\/script") if f.suffix == ".js" else text
    elif f.suffix == ".png":
        kit[f.name] = "data:image/png;base64," + base64.b64encode(f.read_bytes()).decode()

KIT_REF = r"(?:\.\./\.\./source/kit/|kit/)"
pages = {}
for f in sorted(SCREENS.glob("*.html")):
    html = f.read_text(encoding="utf-8")
    html = re.sub(r'<link rel="stylesheet" href="' + KIT_REF + r'([\w.-]+\.css)">',
                  r"<style>@@K:\1@@</style>", html)
    html = re.sub(r'<script src="' + KIT_REF + r'([\w.-]+\.js)"></script>',
                  r"<script>@@K:\1@@</script>", html)
    html = re.sub(r'(["\'])' + KIT_REF + r'([\w.-]+\.png)\1', r"\1@@K:\2@@\1", html)
    pages[f.stem] = html


def js(obj):
    # Escape "</" so the strings are safe even when this file is inlined into a page.
    return json.dumps(obj, ensure_ascii=False).replace("</", "<\\/")


OUT.write_text(
    "// Generated by design/tools/build-screens-bundle.py. Do not edit: regenerate from demo/screens + source/kit.\n"
    "window.SCREENS={kit:" + js(kit) + ",pages:" + js(pages) + ","
    "build(n){return this.pages[n].replace(/@@K:([^@]+)@@/g,(m,k)=>this.kit[k]||'')}};\n"
    "for(const k in SCREENS.pages)SCREENS[k]=true;\n",
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT.parent)}: {len(pages)} screens, {len(kit)} kit files")
